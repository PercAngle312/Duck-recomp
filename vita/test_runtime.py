"""Test semaphore on a host API model, compile the actual Vita queue, audit runtime.

The host model is not Vita OS emulation. Runtime audit failures are recorded as
remaining port work; adapter compile/test failures stop this command.
"""
import argparse
import json
import subprocess
from pathlib import Path
from prepare_runtime import prepare

root = Path(__file__).resolve().parent
p = argparse.ArgumentParser(description=__doc__)
for name in ('runtime', 'recompiler', 'vitasdk', 'adapter-include', 'output'):
    p.add_argument('--' + name, type=Path, required=True)
a = p.parse_args()
out = a.output.resolve()
out.mkdir(parents=True, exist_ok=True)
headers = prepare(a.runtime.resolve(), out)
includes = ['-I' + str(headers), '-I' + str(root / 'include')]
host = subprocess.run(['g++', '-std=c++20', '-O2', '-pthread', '-D__vita__',
    '-I' + str(root / 'tests/fake_sdk'), *includes,
    str(root / 'tests/semaphore.cpp'), '-o', str(out / 'host-semaphore')],
    capture_output=True, text=True)
(out / 'host-compile.log').write_text(host.stdout + host.stderr)
host.check_returncode()
run = subprocess.run([str(out / 'host-semaphore')], capture_output=True, text=True, timeout=30)
(out / 'host-test.log').write_text(run.stdout + run.stderr)
run.check_returncode()
print(run.stdout.strip())
compiler = a.vitasdk.resolve() / 'bin/arm-vita-eabi-g++'
flags = ['-std=c++20', '-mcpu=cortex-a9', '-mfpu=neon', '-mfloat-abi=hard', *includes]
native = subprocess.run([str(compiler), *flags, '-O1', '-c',
    str(root / 'tests/native_queue_probe.cpp'), '-o', str(out / 'native-queue.o')],
    capture_output=True, text=True)
(out / 'native-compile.log').write_text(native.stdout + native.stderr)
native.check_returncode()
symbols = subprocess.check_output([str(a.vitasdk.resolve() / 'bin/arm-vita-eabi-nm'),
    '-u', str(out / 'native-queue.o')], text=True)
for api in ('Create', 'Delete', 'Wait', 'Poll', 'Signal'):
    assert 'sceKernel' + api + 'Sema' in symbols, api
(out / 'native-imports.txt').write_text(symbols)
(out / 'link-main.cpp').write_text('extern "C" int duck_vita_queue_probe();\nint main(){return duck_vita_queue_probe();}\n')
linked = subprocess.run([str(compiler), '-mcpu=cortex-a9', '-mfpu=neon', '-mfloat-abi=hard',
    str(out / 'native-queue.o'), str(out / 'link-main.cpp'), '-o', str(out / 'queue-link-probe')],
    capture_output=True, text=True)
(out / 'native-link.log').write_text(linked.stdout + linked.stderr)
linked.check_returncode()
# Equivalent to the static-library miniz export header generated by CMake.
(out / 'miniz_export.h').write_text('#pragma once\n#define MINIZ_EXPORT\n')
extra = [out, a.adapter_include, a.runtime / 'ultramodern/include', a.runtime / 'librecomp/include',
         a.runtime / 'librecomp/include/librecomp', a.runtime / 'thirdparty',
         a.runtime / 'thirdparty/miniz', a.recompiler / 'include',
         a.recompiler / 'lib/rabbitizer/cplusplus/include',
         a.recompiler / 'lib/rabbitizer/include', a.recompiler / 'lib/fmt/include',
         a.recompiler / 'lib/sljit/sljit_src']
flags += ['-I' + str(path.resolve()) for path in extra]
records = []
for source in ('ultramodern/src/threads.cpp', 'ultramodern/src/events.cpp',
               'ultramodern/src/renderer_context.cpp', 'librecomp/src/recomp.cpp',
               'librecomp/src/rsp.cpp'):
    command = [str(compiler), *flags, '-fsyntax-only', str((a.runtime / source).resolve())]
    result = subprocess.run(command, capture_output=True, text=True)
    log = result.stdout + result.stderr
    assert 'No semaphore wrapper available' not in log, 'Semaphore adapter was not selected'
    filename = source.replace('/', '-') + '.log'
    (out / filename).write_text(log)
    first = next((line.strip() for line in log.splitlines() if 'error:' in line), 'none')
    # Reports are portable and do not reveal private workspace locations.
    for path, label in ((a.runtime, '<runtime>'), (a.recompiler, '<recompiler>'), (out, '<output>')):
        first = first.replace(str(path.resolve()), label)
    records.append(dict(source=source, compile_exit=result.returncode, first_error=first, log=filename))
report = dict(host_api_model_passed=True, host_queue_unique_items=20000,
              vita_queue_object_compiled=True, vita_queue_probe_linked=True, vita_os_tested=False,
              full_game_linked=False, playable_game=False, runtime_audit=records)
(out / 'runtime-report.json').write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps(report, indent=2))
